// 公历转儒略日（内部）
static long ljulianDay(int y, int m, int d) {
    if (m <= 2) { y--; m += 12; }
    return 365L * y + y / 4 - y / 100 + y / 400 + (153L * m - 457) / 5 + d - 306;
}

// 某农历年某月天数（1-12 普通月，返回 29/30）
static int lunarMonthDays(int ly, int m) {
    uint32_t c = LUNAR_CODE[ly - 1900];
    return ((c >> (16 - m)) & 1) ? 30 : 29;
}
// 某农历年闰月月份（0=无闰）
static int lunarLeapMonth(int ly) { return LUNAR_CODE[ly - 1900] & 0xF; }
// 某农历年闰月天数
static int lunarLeapDays(int ly) { return ((LUNAR_CODE[ly - 1900] >> 16) & 1) ? 30 : 29; }
// 某农历年总天数
static int lunarYearDays(int ly) {
    int s = 0;
    for (int m = 1; m <= 12; m++) s += lunarMonthDays(ly, m);
    if (lunarLeapMonth(ly)) s += lunarLeapDays(ly);
    return s;
}

// 公历转农历（ly=农历年 lm=农历月 ld=农历日 leap=是否闰月）
static void solarToLunar(int y, int mo, int d, int& ly, int& lm, int& ld, bool& leap) {
    long off = ljulianDay(y, mo, d) - ljulianDay(1900, 1, 31);
    ly = 1900;
    while (off >= lunarYearDays(ly)) { off -= lunarYearDays(ly); ly++; }
    int lmLeap = lunarLeapMonth(ly);
    leap = false;
    for (int m = 1; m <= 12; m++) {
        int md = lunarMonthDays(ly, m);
        if (off < md) { lm = m; ld = (int)off + 1; return; }
        off -= md;
        if (m == lmLeap) {
            int ld2 = lunarLeapDays(ly);
            if (off < ld2) { lm = m; ld = (int)off + 1; leap = true; return; }
            off -= ld2;
        }
    }
    lm = 12; ld = (int)off + 1;
}

// 日干支 60 甲子序号（0-59），基准 1900-01-31=甲辰(40)
static int dayGanzhiSeq(int y, int mo, int d) {
    long diff = ljulianDay(y, mo, d) - ljulianDay(1900, 1, 31);
    return (int)((40 + diff % 60 + 60) % 60);
}

