// 计算建除十二神索引（0-11）：农历月支(正月=寅) + 日支
static int calcJianChu(int lunarMonth, int dayZhi) {
    int mzhi = (lunarMonth + 1) % 12;   // 正月=寅(2)
    return ((dayZhi - mzhi) + 12) % 12;
}

